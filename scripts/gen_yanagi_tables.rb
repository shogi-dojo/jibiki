#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes lib/generated/romaji_table.rb from the installed yanagi gem's mora
# rules. The validator's romaji check must compile under Spinel, which cannot
# load yanagi's YAML at run time, so the table is frozen into Ruby literals.
#
#   bundle exec ruby scripts/gen_yanagi_tables.rb          # rewrite the file
#   bundle exec ruby scripts/gen_yanagi_tables.rb --check  # exit 1 on drift
require 'yanagi'

module YanagiTables
  module_function

  TARGET = File.expand_path('../lib/generated/romaji_table.rb', __dir__)

  def source
    rows = Yanagi::Rules.mora_map.sort_by { |kana, _| kana.to_s }.map do |kana, info|
      romaji = info[:romaji].nil? ? kana.to_s : info[:romaji].to_s
      "    #{kana.to_s.inspect} => #{romaji.inspect}"
    end
    <<~RUBY
      # frozen_string_literal: true

      # GENERATED by scripts/gen_yanagi_tables.rb from yanagi #{Yanagi::VERSION}
      # (data/mora.yml). Do not edit: rerun the script after a yanagi upgrade.
      module Romaji
        # Kana (one mora, possibly two characters) => Hepburn romaji.
        TABLE = {
      #{rows.join(",\n")}
        }.freeze
      end
    RUBY
  end
end

if __FILE__ == $PROGRAM_NAME
  if ARGV.include?('--check')
    current = File.exist?(YanagiTables::TARGET) ? File.read(YanagiTables::TARGET, encoding: 'UTF-8') : ''
    abort "#{YanagiTables::TARGET} is out of date: rerun scripts/gen_yanagi_tables.rb" unless current == YanagiTables.source
    puts 'romaji table is current'
  else
    File.write(YanagiTables::TARGET, YanagiTables.source)
    puts "wrote #{YanagiTables::TARGET}"
  end
end
