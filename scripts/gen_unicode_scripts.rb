#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes lib/generated/unicode_scripts.rb: the Han and Cyrillic scripts as
# explicit codepoint classes. Spinel's regexp engine has the Unicode general
# categories but not scripts (\p{Han} is a RegexpError there), so the classes
# are generated from this CRuby's own \p{...} tables.
#
#   ruby scripts/gen_unicode_scripts.rb          # rewrite the file
#   ruby scripts/gen_unicode_scripts.rb --check  # exit 1 on drift
module UnicodeScriptTables
  module_function

  TARGET = File.expand_path('../lib/generated/unicode_scripts.rb', __dir__)
  SCRIPTS = { 'HAN' => /\p{Han}/, 'CYRILLIC' => /\p{Cyrillic}/ }.freeze

  def codepoints
    (0..0x10FFFF).reject { |cp| cp.between?(0xD800, 0xDFFF) }
  end

  def ranges(regexp)
    out = []
    codepoints.each do |cp|
      next unless [cp].pack('U').match?(regexp)

      if out.last && out.last[1] == cp - 1
        out.last[1] = cp
      else
        out << [cp, cp]
      end
    end
    out
  end

  def klass(regexp)
    ranges(regexp).map do |first, last|
      first == last ? format('\u{%X}', first) : format('\u{%X}-\u{%X}', first, last)
    end.join
  end

  def source
    constants = SCRIPTS.map { |name, regexp| "  #{name} = /[#{klass(regexp)}]/" }
    <<~RUBY
      # frozen_string_literal: true

      # GENERATED by scripts/gen_unicode_scripts.rb from Ruby #{RUBY_VERSION}
      # (Unicode #{RbConfig::CONFIG['UNICODE_VERSION']}). Do not edit.
      module UnicodeScripts
      #{constants.join("\n")}
      end
    RUBY
  end
end

if __FILE__ == $PROGRAM_NAME
  if ARGV.include?('--check')
    current = File.exist?(UnicodeScriptTables::TARGET) ? File.read(UnicodeScriptTables::TARGET, encoding: 'UTF-8') : ''
    abort "#{UnicodeScriptTables::TARGET} is out of date: rerun the script" unless current == UnicodeScriptTables.source
    puts 'unicode script classes are current'
  else
    File.write(UnicodeScriptTables::TARGET, UnicodeScriptTables.source)
    puts "wrote #{UnicodeScriptTables::TARGET}"
  end
end
